def f7(id, question, path_fns, hops, difficulty, notes, subsystem, extra_ev=()):
    assert len(hops) == len(path_fns) - 1 and 3 <= len(hops) <= 6, id
    ghops, lines = [], []
    for (a, b), h in zip(zip(path_fns, path_fns[1:]), hops):
        kind, file, line, expect = h[:4]
        got = enclosing_name(file, line)
        want = h[4] if len(h) > 4 and h[4] else a
        if got != want:
            raise AssertionError("%s: hop %s->%s site %s:%d is in %r" % (id, a, b, file, line, got))
        lines.append(loc(file, line, expect))
        g = {"from": a, "to": b, "kind": kind, "site": "%s:%d" % (file, line)}
        if len(h) > 5:
            reg = h[5]
            g["via"] = reg[0]
            g["registration"] = "%s:%d" % (reg[1], reg[2])
            lines.append(loc(reg[1], reg[2], reg[3]))
        ghops.append(g)
    e = {"cmd": "sed -n '<line>p' <file>   # one per line below: call site of each hop, in path order, "
                "followed by the table registration for dispatch hops",
         "lines": lines}
    gold = {"path": path_fns, "alternatives_ok": True, "hops": ghops,
            "crosses_ops_table": any(g["kind"] != "call" for g in ghops)}
    add(id, "F7", question, "%s -> %s" % (path_fns[0], path_fns[-1]), gold, [e] + list(extra_ev),
        difficulty, notes, subsystem)


