# F3  direct callers
# --------------------------------------------------------------------------------------
def f3(id, question, name, definition, callers, difficulty, notes, subsystem):
    cmd = r"rg -n '\b%s\s*\(' -g '!Documentation' -g '!tools'" % name
    out = run(cmd)
    declared = {}
    for path, fn, lines in callers:
        for l in lines:
            declared[(path, l)] = fn
    seen = set()
    other = []
    for path, line, text in hits(out):
        if (path, line) in declared:
            got = enclosing_name(path, line)
            if got != declared[(path, line)]:
                raise AssertionError("%s: %s:%d enclosing function is %r, gold says %r"
                                     % (id, path, line, got, declared[(path, line)]))
            if is_comment(text):
                raise AssertionError("%s: %s:%d is a comment" % (id, path, line))
            seen.add((path, line))
        elif (path, line) == definition:
            other.append({"loc": "%s:%d" % (path, line), "kind": "definition"})
        elif is_comment(text):
            other.append({"loc": "%s:%d" % (path, line), "kind": "comment"})
        elif enclosing_name(path, line) is None and re.search(r"[;,]\s*$", text):
            other.append({"loc": "%s:%d" % (path, line), "kind": "declaration"})
        else:
            raise AssertionError("%s: unclassified hit %s:%d: %s" % (id, path, line, text))
    missing = set(declared) - seen
    if missing:
        raise AssertionError("%s: gold call sites not in rg output: %s" % (id, missing))
    refs = run(r"rg -n -w '%s' -g '!Documentation' -g '!tools' | rg -v '%s\s*\('" % (name, name))
    addr_taken = [h for h in hits(refs) if not is_comment(h[2]) and "EXPORT_SYMBOL" not in h[2]]
    if addr_taken:
        raise AssertionError("%s: non-call references need review: %s" % (id, addr_taken))
    evidence = [
        {"cmd": cmd,
         "lines": [loc(p, l, name) for (p, l) in sorted(declared)],
         "other_hits": other},
        {"cmd": r"rg -n -w '%s' -g '!Documentation' -g '!tools' | rg -v '%s\s*\('   "
                r"# only comments / EXPORT_SYMBOL remain: the name is never used as a pointer"
                % (name, name),
         "lines": []},
        read_ev(*sorted(set((p, enclosing_header(p, l)[0], fn) for (p, l), fn in declared.items()))),
    ]
    gold = {"callers": [{"file": p, "function": fn, "lines": ls} for p, fn, ls in callers],
            "complete": True, "call_sites": len(declared),
            "definition": "%s:%d" % definition}
    add(id, "F3", question, name, gold, evidence, difficulty, notes, subsystem)


