Q = []


def ev(cmd, *locs):
    """Evidence item: run cmd, require each (path, line, expect) to be shown by it."""
    out = run(cmd)
    lines = []
    for path, line, expect in locs:
        lines.append(loc(path, line, expect))
        if not output_has(out, cmd, path, line):
            raise AssertionError("command %r does not show %s:%d" % (cmd, path, line))
    return {"cmd": cmd, "lines": lines}


def ev_count(cmd, expected):
    """Evidence item whose whole output is a single number."""
    out = run(cmd).strip()
    if out != str(expected):
        raise AssertionError("command %r printed %r, expected %r" % (cmd, out, expected))
    return {"cmd": cmd, "lines": [], "output": out}


def read_ev(*locs):
    """Evidence item for plain reading: each line is `sed -n '<line>p' <file>`."""
    return {"cmd": "sed -n '<line>p' <file>   # one per line below",
            "lines": [loc(p, l, e) for p, l, e in locs]}


def add(id, family, question, symbol, gold, evidence, difficulty, notes, subsystem):
    assert difficulty in ("easy", "medium", "hard")
    Q.append({"id": id, "family": family, "subsystem": subsystem, "question": question,
              "symbol": symbol, "gold": gold, "evidence": evidence,
              "difficulty": difficulty, "notes": notes})


