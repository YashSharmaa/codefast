# --------------------------------------------------------------------------------------
# F9  struct field writers
# --------------------------------------------------------------------------------------
# What a write to THIS struct's field looks like textually (receiver names used in the tree).
# A hit that matches the guard but is not a listed writer aborts the build, so a real writer
# can never be silently filed under an other-struct label.
GUARDS = {
    "F9-01": r"\b(p|idle|tsk|task|prev|next|donor)->on_rq\s*=($|[^=])|\(&?(p|idle|tsk|task)->on_rq",
    "F9-02": r"\bq->nr_requests\s*=($|[^=])",
    "F9-03": r"(\bmnt|\bm|\bp|real_mount\(\w+\))->mnt_ns\s*=($|[^=])|WRITE_ONCE\(",
    "F9-04": r"\b\w*isec->sid\s*=($|[^=])|&\w*isec->sid",
    "F9-05": r"\bmm->locked_vm\s*(=($|[^=])|\+=|-=)",
    "F9-06": r"ctrl(->|\.)queue_count\s*(=($|[^=])|\+\+|--|\+=|-=)",
    "F9-07": r"thread\s*(\.|->)\s*sp\s*(=($|[^=])|\+=|-=)|\bt->sp\b",
    "F9-08": r"ctx->cq_entries\s*=($|[^=])",
}


def f9(id, question, struct, field, decl, writers, noise, proofs, complete, difficulty, notes,
       subsystem, paths="", noise_locs=None, extra_ev=(), guard=None, **extra):
    """guard: regex describing what a write to THIS struct's field looks like at the text level
    (receiver names used in the tree); a non-writer hit matching it aborts the build, so a real
    writer cannot be silently filed under an other-struct label."""
    noise_locs = noise_locs or {}
    guard = guard or GUARDS[id]
    cmd = field_write_cmd(field, paths)
    out = run(cmd)
    declared = {}
    for path, fn, lines in writers:
        for l in lines:
            declared[(path, l)] = fn
    seen, summary, total = set(), {}, 0
    for path, line, text in hits(out):
        total += 1
        if (path, line) in declared:
            got = enclosing_name(path, line)
            if got != declared[(path, line)]:
                raise AssertionError("%s: %s:%d enclosing is %r not %r" % (id, path, line, got, declared[(path, line)]))
            seen.add((path, line))
            continue
        if (path, line) in noise_locs:
            label = noise_locs[(path, line)]
        elif is_comment(text):
            label = "comment"
        else:
            if guard and re.search(guard, text):
                raise AssertionError("%s: guard matched a non-writer hit %s:%d: %s" % (id, path, line, text.strip()))
            for rx, lab in noise:
                if re.search(rx, text):
                    label = lab
                    break
            else:
                raise AssertionError("%s: unclassified hit %s:%d: %s" % (id, path, line, text.strip()))
        summary[label] = summary.get(label, 0) + 1
    missing = set(declared) - seen
    if missing:
        raise AssertionError("%s: writer lines not in rg output: %s" % (id, sorted(missing)))
    e1 = {"cmd": cmd, "lines": [loc(p, l, field) for (p, l) in sorted(declared)],
          "total_hits": total, "writer_hits": len(declared), "other_hits_by_kind": summary}
    e2 = {"cmd": "sed -n '<line>p' <file>   # one per line below: field declaration, then the "
                 "declaration that fixes each writer's receiver type",
          "lines": [loc(*decl)] + [loc(*p) for p in proofs]}
    gold = {"struct": struct, "field": field,
            "writers": [{"file": p, "function": fn, "lines": ls} for p, fn, ls in writers],
            "complete": complete}
    gold.update(extra)
    add(id, "F9", question, "%s.%s" % (struct, field), gold, [e1, e2] + list(extra_ev),
        difficulty, notes, subsystem)


