def f4(id, question, name, path, line, callees, macros, indirect, difficulty, notes, subsystem):
    b = line
    while not src(path, b).startswith("{"):
        b += 1
    hdr, brace, close, toks = body_tokens(path, b + 1)
    assert hdr == line, (id, hdr, line)
