def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "questions.jsonl")
    ids = [q["id"] for q in Q]
    assert len(ids) == len(set(ids)) == 72, len(ids)
    fam = {}
    for q in Q:
        fam[q["family"]] = fam.get(q["family"], 0) + 1
    assert all(v == 8 for v in fam.values()) and len(fam) == 9, fam
