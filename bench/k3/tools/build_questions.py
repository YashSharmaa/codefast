"""Builds bench/k3/questions.jsonl from the hand-derived gold answers below.

The gold answers are DATA in this file (typed in after reading the kernel source). The
script does not derive them; it only re-checks them against the pinned tree while writing:
  * every evidence command is executed and must show every evidence line it claims,
  * every cited source line must contain the substring recorded next to it,
  * F3: every textual hit of NAME( in the tree must be either a listed call site (whose
        enclosing function must match), the definition, a declaration or a comment,
  * F4: the set of identifier( tokens in the function body must equal
        callees + macros + indirect (so nothing in the body is unaccounted for),
  * F9: every textual write-like hit of the field must be either a listed writer line or
        match an explicitly labelled other-struct / read pattern.
Any mismatch aborts the build.

Usage: python3 tools/build_questions.py [out.jsonl]
"""
