def f2(id, question, symbol, path, first, last, must, difficulty, notes, subsystem, extra_ev=()):
    text = norm(" ".join(src(path, n) for n in range(first, last + 1)))
    for m in must:
        if norm(m) not in text:
            raise AssertionError("%s: %r not in %s:%d-%d" % (id, m, path, first, last))
    e = ev("sed -n '%d,%dp' %s" % (first, last, path),
           *[(path, n, None) for n in range(first, last + 1) if src(path, n).strip()])
    add(id, "F2", question, symbol, {"file": path, "line": first, "must_contain": must},
        [e] + list(extra_ev), difficulty, notes, subsystem)


